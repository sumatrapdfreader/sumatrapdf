// must not crash or recurse without end; converting may fail
static void LitMustNotCrash(const u8* d, int n) {
    Str epub = LitToEpubConvert(Str((const char*)d, n));
    str::Free(epub);
}

void LitDoc_UnitTests() {
#if IS_DEBUG
    utassert(LitDoc_UnitTestManifest());
    utassert(LitDoc_UnitTestDes());
    utassert(LitDoc_UnitTestDesThreads());
    utassert(LitDoc_UnitTestLzxOverrun());
    utassert(LitDoc_UnitTestZipName());
    utassert(LitDoc_UnitTestSectionNames());
    utassert(LitDoc_UnitTestOpfStrayClose());
#endif
    LitMustReject(MkLitHdrLenWrap());
    LitMustReject(MkLitPosOverflow());
    LitMustReject(MkLitDirRangeWrap());
    LitMustReject(MkLitContentOffsetNeg());
    LitMustReject(MkLitSectionOffsetWrap());
    LitMustReject(MkLitNameLenWrap());
    LitMustNotCrash(kLitIssue6569Av, (int)sizeof(kLitIssue6569Av));
    LitMustNotCrash(kLitIssue6569Recursion, (int)sizeof(kLitIssue6569Recursion));
}
