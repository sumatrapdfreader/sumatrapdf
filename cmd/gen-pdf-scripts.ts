import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const scripts = {
  "load-a-pdf.js": "Load a PDF",
  "create-a-pdf.js": "Create a PDF",
  "add-an-annotation.js": "Add an annotation",
  "convert-pdf-to-plain-text.js": "Convert PDF to plain text",
  "convert-pdf-to-images.js": "Convert PDF to images",
  "create-pdf.js": "Create PDF",
  "create-pdf-low-level.js": "Create PDF (low level)",
  "merge-pdfs.js": "Merge PDFs",
  "create-pdf-with-thumbnails.js": "Create PDF with thumbnails",
  "draw-graphics-with-device.js": "Draw graphics with Device",
  "trace-device.js": "Trace device",
  "pdf-dejpx.js": "Replace JPEG 2000 images",
  "copy-outline.js": "Copy outline",
  "pdf-bake.js": "Bake annotations",
};

const root = join(import.meta.dir, "..");
let out = "// Generated by cmd/gen-pdf-scripts.ts.\nstatic const PDFScriptExample kPDFScripts[] = {\n";
for (const [file, title] of Object.entries(scripts)) {
  const source = readFileSync(join(root, "src/pdf-scripts", file), "utf8").replaceAll("\r\n", "\n");
  if (source.includes(')JS"')) throw new Error(`Raw-string delimiter in ${file}`);
  out += `    {StrL(${JSON.stringify(title)}), StrL(R"JS(${source})JS")},\n`;
}
out += "};\n";
writeFileSync(join(root, "src/shared/PDFScriptExamples.inc"), out);
